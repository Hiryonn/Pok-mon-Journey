import * as ResEdit from 'resedit'; import * as PE from 'pe-library'; import fs from 'fs';
const [,, input, ico, output] = process.argv;
const exe = PE.NtExecutable.from(fs.readFileSync(input), { ignoreCert: true });
const res = PE.NtExecutableResource.from(exe);
const iconFile = ResEdit.Data.IconFile.from(fs.readFileSync(ico));
const g = ResEdit.Resource.IconGroupEntry.fromEntries(res.entries)[0];
ResEdit.Resource.IconGroupEntry.replaceIconsForResource(res.entries, g.id, g.lang, iconFile.icons.map((i) => i.data));
const vi = ResEdit.Resource.VersionInfo.fromEntries(res.entries)[0];
const lang = vi.getAllLanguagesForStringValues()[0];
vi.setStringValues(lang, { ProductName: 'Pokémon Studio Extra', FileDescription: 'Pokémon Studio Extra' });
vi.outputToResourceEntries(res.entries);
res.outputResource(exe);
fs.writeFileSync(output, Buffer.from(exe.generate()));
console.log('ok', JSON.stringify(vi.getStringValues(lang)));
